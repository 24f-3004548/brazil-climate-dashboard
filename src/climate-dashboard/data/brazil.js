const SECTOR_KEYS = ["agriculture", "energy", "land_use", "industrial", "waste"];

function normalizeSectorShares(row) {
  const sectorTotal = SECTOR_KEYS.reduce((sum, key) => sum + Number(row[key] ?? 0), 0);

  // New source files can provide absolute values; convert to shares for chart components.
  if (!Number.isFinite(sectorTotal) || sectorTotal <= 0) {
    return row;
  }

  if (sectorTotal <= 1.000001) {
    return row;
  }

  const normalized = { ...row };
  SECTOR_KEYS.forEach((key) => {
    normalized[key] = Number(row[key] ?? 0) / sectorTotal;
  });
  return normalized;
}

export const BRAZIL = BRAZIL_RAW.map(normalizeSectorShares);
